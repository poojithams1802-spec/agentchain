def test_failed_sandbox_execution_does_not_create_finding(monkeypatch):
    planner = FakePlanner()

    def fake_execute(decision, experiment_id):
        return {
            "status": "failed",
            "test": decision.selected_test,
            "finding": None,
            "severity": None,
            "evidence": "Sandbox execution failed.",
            "confidence": 0.0,
        }

    monkeypatch.setattr("adaptive_loop.execute_planned_test", fake_execute)

    planner_input = PlannerInput(
        available_tests=["permission_test"]
    )

    loop = AdaptiveLoop(planner=planner)

    findings = loop.run(
        planner_input=planner_input,
        experiment_id="exp-006",
        max_tests=1,
    )

    assert findings == []

    # The attempted test is still recorded.
    assert planner_input.previous_tests == ["permission_test"]

    # No Finding should be created for a failed sandbox execution.
    assert planner_input.findings == []


